// 公開日。
//
// 8月10日（月）の 0 時に、小学校のころの二択とお題がまとめて出る。
// 以降は毎週月曜に、中学 → 高校 → 二十代と進む。
//
// この日より前にサイトを開いた人には、二択もお題も 1 件も見えない。
// 何も出ない画面をそのまま見せると「壊れている」「過疎っている」と読まれるので、
// 開く日を先に伝える。空っぽに見えるのと、開店前だと分かっているのとでは、
// 同じ画面でも受け取り方がまるで違う。
//
// 公開日を過ぎたら、この案内は自動で出なくなる。日付を手で消す必要はない。

/** 公開の瞬間（日本時間 2026年8月10日 0時）。 */
export const LAUNCH_AT = new Date("2026-08-10T00:00:00+09:00");

/** 画面に出す表記。 */
export const LAUNCH_LABEL = "8月10日（月）";

/**
 * まだ公開前か。
 *
 * Server Component の本体で new Date() を直接呼ぶと React Compiler の
 * lint に叱られるので、判定はこの関数に閉じ込めてある。
 */
export function isBeforeLaunch(now: Date = new Date()): boolean {
  return now.getTime() < LAUNCH_AT.getTime();
}
